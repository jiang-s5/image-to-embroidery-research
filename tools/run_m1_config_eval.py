from __future__ import annotations

import argparse
import csv
import json
import subprocess
import sys
from pathlib import Path
from typing import Any

from score_unified import score_metrics, safe_float


DEFAULT_BASE_ARGS = {
    "--geometry-planner": True,
    "--model-path-order": True,
    "--use-continuity-planner": True,
    "--serpentine-fill": True,
}


def read_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def append_args(command: list[str], args: dict[str, Any]) -> None:
    for key, value in args.items():
        if isinstance(value, bool):
            if value:
                command.append(key)
        elif value is not None and str(value) != "":
            command.extend([key, str(value)])


def run(command: list[str], cwd: Path) -> None:
    print(" ".join(command), flush=True)
    completed = subprocess.run(command, cwd=cwd, text=True, capture_output=True)
    if completed.returncode != 0:
        if completed.stdout:
            print(completed.stdout)
        if completed.stderr:
            print(completed.stderr, file=sys.stderr)
        completed.check_returncode()


def write_csv(rows: list[dict[str, Any]], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        path.write_text("", encoding="utf-8")
        return
    keys: list[str] = []
    seen: set[str] = set()
    for row in rows:
        for key in row:
            if key not in seen:
                seen.add(key)
                keys.append(key)
    with path.open("w", newline="", encoding="utf-8-sig") as handle:
        writer = csv.DictWriter(handle, fieldnames=keys, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)


def load_score_config(path: Path) -> tuple[dict[str, float], dict[str, float]]:
    config = json.loads(path.read_text(encoding="utf-8"))
    thresholds = config.get("thresholds", {}) if isinstance(config, dict) else {}
    weights = config.get("weights", {}) if isinstance(config, dict) else {}
    return (
        {str(key): safe_float(value) for key, value in thresholds.items()},
        {str(key): safe_float(value) for key, value in weights.items()},
    )


def hard_score_proxy(row: dict[str, Any]) -> float:
    return (
        safe_float(row.get("visible_connector_count")) / 3.0
        + safe_float(row.get("off_mask_stitch_length_mm")) / 8.0
        + safe_float(row.get("jump_count")) / 25.0
        + safe_float(row.get("trim_count")) / 20.0
        + safe_float(row.get("unified_loss"))
    )


def write_report(rows: list[dict[str, Any]], path: Path) -> None:
    if not rows:
        path.write_text("# M1 Config Eval\n\nNo rows.\n", encoding="utf-8")
        return
    avg = lambda key: sum(safe_float(row.get(key)) for row in rows) / max(1, len(rows))
    lines = [
        "# M1 Config Regressor DST Evaluation",
        "",
        "These rows were generated by running the predicted continuous M1 planner configs through DST/PES export and executability evaluation.",
        "",
        "| Samples | Mean Unified | Mean Hard Score | Mean Exec | Mean Visual Risk | Mean Jumps | Mean Trims | Mean Visible | Mean Off-Mask mm |",
        "| ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
        "| {n} | {unified:.6f} | {hard:.6f} | {exec_score:.6f} | {visual:.6f} | {jumps:.3f} | {trims:.3f} | {visible:.3f} | {offmask:.3f} |".format(
            n=len(rows),
            unified=avg("unified_loss"),
            hard=avg("hard_score"),
            exec_score=avg("exec_score"),
            visual=avg("visual_risk"),
            jumps=avg("jump_count"),
            trims=avg("trim_count"),
            visible=avg("visible_connector_count"),
            offmask=avg("off_mask_stitch_length_mm"),
        ),
        "",
        "## Per-Sample",
        "",
        "| Sample | Nearest Preset | Unified | Hard Score | Hard Level | Jumps | Trims | Visible | Off-Mask mm |",
        "| --- | --- | ---: | ---: | --- | ---: | ---: | ---: | ---: |",
    ]
    for row in rows:
        lines.append(
            "| {sample_id} | {nearest_preset} | {unified_loss:.6f} | {hard_score:.6f} | {quality_level} | {jump_count:.3f} | {trim_count:.3f} | {visible_connector_count:.3f} | {off_mask_stitch_length_mm:.3f} |".format(
                sample_id=row["sample_id"],
                nearest_preset=row.get("nearest_preset", ""),
                unified_loss=safe_float(row.get("unified_loss")),
                hard_score=safe_float(row.get("hard_score")),
                quality_level=row.get("quality_level", ""),
                jump_count=safe_float(row.get("jump_count")),
                trim_count=safe_float(row.get("trim_count")),
                visible_connector_count=safe_float(row.get("visible_connector_count")),
                off_mask_stitch_length_mm=safe_float(row.get("off_mask_stitch_length_mm")),
            )
        )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description="Run DST/evaluator loop using M1-predicted continuous planner configs.")
    parser.add_argument("--predictions-json", required=True)
    parser.add_argument("--output-dir", default="results/m1_config_regressor/latest_pair_20260618_eval")
    parser.add_argument("--checkpoint", default="checkpoints/best_model13_multiformat_all_vector_continuity.pt")
    parser.add_argument("--planner-config", default="configs/relation_planner.yaml")
    parser.add_argument("--score-config", default="configs/sweep_b1.yaml")
    parser.add_argument("--reuse", action="store_true")
    parser.add_argument("--cpu", action="store_true")
    args = parser.parse_args()

    root = Path.cwd()
    predictions = read_json(Path(args.predictions_json))
    if not isinstance(predictions, list):
        raise SystemExit("Predictions JSON must contain a list.")
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    thresholds, weights = load_score_config(Path(args.score_config))

    rows: list[dict[str, Any]] = []
    for item in predictions:
        if not isinstance(item, dict):
            continue
        sample_id = str(item.get("sample_id", ""))
        paths = item.get("paths", {})
        config_args = item.get("predicted_config", {})
        if not isinstance(paths, dict) or not isinstance(config_args, dict):
            continue
        case_out = output_dir / sample_id
        eval_json = case_out / "executability_eval.json"
        if not args.reuse or not eval_json.exists():
            infer_command = [
                sys.executable,
                "infer_model3_portrait_hybrid.py",
                str(paths.get("input", "")),
                "--checkpoint",
                args.checkpoint,
                "--output-dir",
                str(case_out),
                "--planner-config",
                args.planner_config,
                "--external-foreground-mask",
                str(paths.get("mask", "")),
            ]
            if args.cpu:
                infer_command.append("--cpu")
            append_args(infer_command, DEFAULT_BASE_ARGS)
            append_args(infer_command, config_args)
            run(infer_command, root)

            eval_command = [
                sys.executable,
                "tools/eval_executability.py",
                "--pred",
                str(case_out / "embroidery_output.dst"),
                "--mask",
                str(case_out / "hybrid_export_mask.png"),
                "--report",
                str(eval_json),
                "--target-width-mm",
                "90",
                "--max-stitch-mm",
                "4",
                "--high-risk-jump-mm",
                "8",
            ]
            if paths.get("target"):
                eval_command.extend(["--gt", str(paths.get("target"))])
            run(eval_command, root)

        payload = read_json(eval_json)
        pred = payload.get("pred", payload)
        if not isinstance(pred, dict):
            pred = {}
        score = score_metrics(pred, thresholds=thresholds, weights=weights)
        rows.append(
            {
                "sample_id": sample_id,
                "nearest_preset": item.get("nearest_preset", ""),
                **{key: pred.get(key, "") for key in sorted(set(score["score_thresholds"]) | {"round_trip_parse_success", "stitch_count", "stitch_path_mm"})},
                "unified_loss": score["unified_loss"],
                "exec_score": score["exec_score"],
                "visual_risk": score["visual_risk"],
                "quality_level": score["quality_level"],
            }
        )
        rows[-1]["hard_score"] = round(hard_score_proxy(rows[-1]), 8)

    write_csv(rows, output_dir / "m1_config_eval_results.csv")
    (output_dir / "m1_config_eval_results.json").write_text(json.dumps(rows, ensure_ascii=False, indent=2), encoding="utf-8")
    write_report(rows, output_dir / "m1_config_eval_report.md")
    print(json.dumps({"samples": len(rows), "output_dir": str(output_dir)}, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
